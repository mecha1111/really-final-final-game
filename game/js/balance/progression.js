  //
  //   근본 원인은 "플레이어 수입에 상한이 있는데 할당량만 지수로 오른다"였다:
  //     파일 수입 = 180초 × 2.24MB/s ≈ 404MB — 제한시간과 파일 등급 비율로
  //       고정이라 구간이 올라도 안 커진다.
  //     콤보 수입 = 100~150MB (스폰 수에 약하게 비례)
  //     → 총 상한 450~540MB가 사실상 평탄한데 quota는 250×1.15^n으로 올라가
