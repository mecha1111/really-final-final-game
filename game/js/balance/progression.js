  //   결과, 1.15로는 숙련 플레이어(초당 3.3클릭·조준 85%)도 5구간을 못 깼다
  //   (달성률 87.9%, 3판 0/3). 무한모드는 더 심해서 첫 층이 이론 상한 98.3%로
