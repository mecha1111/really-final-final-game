// 신규 방해꾼(hourglass/zombie) 시트 폴백
//
// 2026-09: 구글 시트 enemies 탭에 아직 이 두 행이 없다. 시트에 추가되기 전까지는
// 여기 값으로 동작하고, 시트에 실제 행이 생기면(같은 id) 그쪽이 자동으로 이긴다
// (아래 applyEnemyFallbacks의 .some 검사) — 이 표를 나중에 지울 필요조차 없다.
//
// 시트에 실제로 추가할 때 필요한 컬럼(enemies 탭 헤더와 동일 순서):
//   id,name_kr,type,size_w,size_h,hit_w,hit_h,speed,move_pattern,hp,dps,
//   stops_upload,lifetime,weight,min_stage,action,special_effect
// 아래 두 객체의 값을 그대로 그 행에 옮기면 된다. hp/dps/stops_upload/action은
// 게임 동작을 직접 좌우하니(hourglass는 action=none이라야 "클릭=일반 처치"가
// 아니라 함정 분기를 타고, zombie는 action=click이라야 보통 잡몹처럼 클릭된다)
// 값이 아니라 어휘 자체를 바꾸면(예: action에 다른 문구) 동작이 깨진다.
// ---------------------------------------------------------------------------
const ENEMY_SHEET_FALLBACK = [
  {
    id: 'hourglass', name_kr: '모래시계 함정', type: 'B',
    size_w: 90, size_h: 110, hit_w: 90, hit_h: 110,
    speed: 25, move_pattern: '떠다님',
    hp: 0, dps: 0, stops_upload: false, lifetime: 7,
    weight: 8, min_stage: 3, action: 'none', special_effect: '클릭시 조작불능 1초+콤보리셋',
  },
  {
    id: 'zombie', name_kr: '좀비 프로세스', type: 'B',
    size_w: 90, size_h: 90, hit_w: 100, hit_h: 100,
    speed: 45, move_pattern: '직선+벽반사',
    hp: 1, dps: 2, stops_upload: false, lifetime: 9,
    weight: 12, min_stage: 4, action: 'click', special_effect: '처치 3초 후 1회 부활',
  },
];

/**
 * gameData.enemies(시트든 로컬CSV든 하드코딩이든 어느 소스로 로드됐든)에 위 두
 * 종류가 아직 없으면 채워 넣는다. main.js가 loadGameData() 직후(최초 로드·리로드
 * 버튼 둘 다 applyLoadedData를 거치므로 한 곳만 부르면 됨) 호출한다.
 */
export function applyEnemyFallbacks() {
  for (const fallback of ENEMY_SHEET_FALLBACK) {
    if (!gameData.enemies.some((e) => e.id === fallback.id)) {
      gameData.enemies.push(fallback);
    }
  }
}

/**
 * config.stage.enemyUnlockPlan(해금 배치의 정본)을 로드된 enemies 데이터에 입힌다.
 * main.js가 applyEnemyFallbacks() 바로 뒤에 부른다(폴백으로 채워 넣은 행까지
 * 함께 맞추기 위해 순서가 중요하다).
 *
 * 표에 없는 id는 손대지 않는다 — 나중에 시트에 새 방해꾼이 생겨도 여기 표에
 * 올리기 전까지는 시트 값 그대로 돈다(모르는 놈을 임의로 0구간에 풀어놓지 않는다).
 *
 * @returns {Array<{id: string, from: number, to: number}>} 실제로 덮어쓴 항목
 */
export function applyEnemyUnlockPlan() {
  const plan = config.stage.enemyUnlockPlan;
  const changed = [];
  for (const spec of gameData.enemies) {
    const want = plan[spec.id];
    if (want === undefined) continue;
    const had = spec.min_stage ?? 1;
    if (had === want) continue;
    spec.min_stage = want;
    changed.push({ id: spec.id, from: had, to: want });
  }
  // 시트와 코드가 다르다는 사실을 조용히 묻지 않는다 — 시트를 고치면 이 줄이
  // 저절로 사라지므로, 로그가 없어지는 것이 곧 "시트가 정본과 같아졌다"는 신호다.
  if (changed.length && config.debug.enabled) {
    console.warn(
      `[unlock] 시트 min_stage를 config.stage.enemyUnlockPlan으로 덮어썼다(${changed.length}건) — ` +
        `시트를 이 값으로 고치면 이 경고는 사라진다: ` +
        changed.map((c) => `${c.id} ${c.from}→${c.to}`).join(', '),
    );
  }
  return changed;
}

/**
 * 지금 캔버스가 기준 해상도(config.canvas.baseWidth)보다 몇 배 큰지/작은지.
 * enemies.js가 이 값을 방해꾼 크기·히트박스·속도에 곱해서, 어떤 해상도로
 * 바꿔도 화면에서 차지하는 비율이 같아 보이게 한다. applyStageToConfig()
 * 이후에 불러야 실제 캔버스 폭을 반영한다(그 전엔 폴백 width 기준).
 */
export function getScaleFactor() {
  return config.canvas.width / config.canvas.baseWidth;
}

/**
 * 위 getScaleFactor()와 같은 개념이지만 방해꾼이 아니라 HUD/타이틀/난이도
 * 카드/결과 화면 전용 — 기준 폭이 다르다(uiBaseWidth=1920).
 * ui/render.js가 이 값으로 ctx.scale()을 걸어서 그 안의 그리기 함수들은
 * 항상 1920 기준 숫자 그대로 쓰면 된다.
 */
export function getUiScaleFactor() {
  return config.canvas.width / config.canvas.uiBaseWidth;
}

/**
 * 캔버스 백킹스토어(실제 픽셀 수) 1개당 논리 픽셀 몇 개인지.
 *
 * 게임 로직·좌표는 전부 "논리 해상도"(config.canvas.width, 시트의 canvas_w)를 쓰고,
 * 백킹스토어는 화면에 실제로 깔리는 device px에 맞춰 따로 키운다(ui/canvasFit.js).
 * 둘을 잇는 게 이 배율이다 — ui/render.js가 매 프레임 ctx.setTransform으로 걸어주므로
 * 그리기 코드는 예전처럼 논리 좌표만 쓰면 된다.
 *
 * 이렇게 분리한 이유: 예전엔 백킹스토어가 시트의 960x540으로 고정이라, 화면이 그보다
 * 크면(예: 1310) 캔버스에 그린 글씨(대기/결과 화면)가 비트맵째 확대돼 뭉개졌다.
 * 백킹스토어를 실제 표시 크기에 맞추면 글자가 처음부터 최종 해상도로 그려진다.
 *
 * 방해꾼 크기는 이 값과 무관하게 그대로다 — 논리 크기가 config.canvas.width에
 * 비례하고(getScaleFactor) 표시 배율이 그 역수로 움직여 서로 상쇄된다.
 */
export function getRenderScale(canvas) {
  return canvas.width / config.canvas.width;
}

/**
 * ui/screens.js가 레이아웃 계산에 쓰는 "가상의" 캔버스 크기
 * (1920 기준, 실제 canvas.width/height와는 다를 수 있다). getUiScaleFactor()로
 * 그려질 것을 전제하므로, 실제 캔버스가 몇이든 이 크기 기준으로 좌표를 짜면
 * 항상 올바른 비율로 나온다. 클릭 판정(systems/input.js)도 같은 걸 써야
 * 그리기와 히트박스가 어긋나지 않는다.
 */
export function getUiReferenceCanvas() {
  return {
    width: config.canvas.uiBaseWidth,
    height: config.canvas.uiBaseWidth * (config.canvas.height / config.canvas.width),
  };
}
